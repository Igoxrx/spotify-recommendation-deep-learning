# 1. PREPARAÇÃO E LIMPEZA DOS DADOS (PARA MULTILABEL)
spotify_rede_ml = spotify_dataset.copy()
spotify_rede_ml['key'] = spotify_rede_ml['key'].map(key_dict).fillna(-1).astype(int)
spotify_rede_ml['genre'] = spotify_rede_ml['genre'].replace(replace_dict)

# Isso transforma o problema em multilabel, pois uma música pode ter vários gêneros associados.
genres_per_track = (
    spotify_rede_ml
    .groupby('track_id')['genre']
    .apply(lambda x: list(set(x)))
    .reset_index()
)

features_df = (
    spotify_rede_ml
    .drop(columns=['genre'])
    .drop_duplicates(subset=['track_id'])
    .set_index('track_id')
)

df_multilabel = features_df.join(genres_per_track.set_index('track_id'))

feature_cols = [
    'acousticness', 'danceability', 'duration_ms', 'energy',
    'instrumentalness', 'key', 'liveness', 'loudness',
    'speechiness', 'tempo', 'valence'
]

X = df_multilabel[feature_cols]
y_labels = df_multilabel['genre']

import joblib
mlb = MultiLabelBinarizer()
Y = mlb.fit_transform(y_labels)
joblib.dump(mlb, 'multilabel_binarizer.pkl')


# 2. DIVISÃO EM TREINO E TESTE
X_train, X_test, Y_train, Y_test = train_test_split(X, Y, test_size=0.2, random_state=42)

# 3. ESCALONAMENTO DOS DADOS
scaler = StandardScaler()
X_train_scaled = scaler.fit_transform(X_train)
X_test_scaled = scaler.transform(X_test)

# 4. CRIAÇÃO E TREINAMENTO DA REDE NEURAL (TENSORFLOW/KERAS)-
print("\n--- Construindo e Compilando o modelo TensorFlow/Keras para Multilabel ---")

# Define as dimensões de entrada e saída
input_dim = X_train_scaled.shape[1]
output_dim = Y.shape[1]

# Construção do modelo sequencial
model = Sequential([
    Dense(256, activation='relu', input_shape=(input_dim,)),
    Dropout(0.5),
    Dense(128, activation='relu'),
    Dropout(0.4),
    Dense(64, activation='relu'),
    Dropout(0.3),
    Dense(output_dim, activation='sigmoid')
])

# Compilação do modelo

label_freq = Y_train.mean(axis=0)
class_weights = 1 / (label_freq + 1e-6)
class_weights = class_weights / class_weights.sum() * len(class_weights)

@tf.function
def weighted_binary_crossentropy(y_true, y_pred):
    weights = tf.constant(class_weights, dtype=tf.float32)
    unweighted_loss = tf.keras.losses.binary_crossentropy(y_true, y_pred)
    weighted_loss = unweighted_loss * weights
    return tf.reduce_mean(weighted_loss)


model.compile(
    optimizer='adam',
    loss = tf.keras.losses.BinaryCrossentropy(label_smoothing=0.1),
    # Métricas comuns para avaliar a performance em tarefas de classificação
    metrics=['accuracy', tf.keras.metrics.Precision(), tf.keras.metrics.Recall()]
)

model.summary()

# O EarlyStopping continua sendo uma ótima prática
early_stopping = EarlyStopping(
    monitor='val_precision',
    mode='max',
    patience=15,
    restore_best_weights=True
)

