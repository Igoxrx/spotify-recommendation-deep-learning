# O treinamento é funcionalmente o mesmo
history = model.fit(
    X_train_scaled,
    Y_train,
    epochs=100,
    batch_size=64,
    validation_data=(X_test_scaled, Y_test),
    callbacks=[early_stopping],
    verbose=1
)

