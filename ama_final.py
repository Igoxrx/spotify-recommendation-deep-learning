print("\n--- Avaliando o modelo multilabel ---")

# O método .predict() retorna as probabilidades (entre 0 e 1) para cada classe
y_pred_proba = model.predict(X_test_scaled)

# Se a probabilidade for > 0.5, a classe é considerada presente (1), senão ausente (0)

optimal_thresholds = []

for i in range(Y.shape[1]):
    precision, recall, thresholds = precision_recall_curve(Y_test[:, i], y_pred_proba[:, i])
    f1 = 2 * (precision * recall) / (precision + recall + 1e-6)
    best_threshold = thresholds[np.argmax(f1)]
    optimal_thresholds.append(best_threshold)
optimal_thresholds = np.array(optimal_thresholds)
np.save('optimal_thresholds.npy', optimal_thresholds)

y_pred = np.zeros_like(y_pred_proba)

for i, thresh in enumerate(optimal_thresholds):
    y_pred[:, i] = (y_pred_proba[:, i] > thresh).astype(int)

